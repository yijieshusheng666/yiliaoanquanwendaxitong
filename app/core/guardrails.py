"""急症安全护栏：命中急症关键词直接返回固定提示，不做任何生成。

设计要点：
- 独立于大模型与检索，规则命中即拦截，保证「急症拦截率 100%」。
- 宁可误拦（安全优先），不漏拦。
"""
from __future__ import annotations

# 危及生命急症关键词（与评测测试集一一对应）
EMERGENCY_KEYWORDS = [
    "胸痛", "心梗", "心肌梗死", "绞痛",          # 心脏急症
    "昏迷", "失去意识", "意识不清", "不省人事",    # 意识障碍
    "抽搐", "惊厥", "口吐白沫",                   # 神经系统急症
    "自杀", "轻生", "想死", "服毒", "服药过量", "过量服药",  # 精神行为急症
    "中毒", "休克", "血压测不到",                 # 循环衰竭
    "大出血", "呕血", "咯血", "窒息", "呼吸困难", "无呼吸",  # 呼吸/出血
    "心跳骤停", "心搏骤停",                       # 心跳呼吸骤停
]

# 高危词误伤豁免：当急症关键词出现在以下「否定/非急症」语境时不拦截（如"……不是……"）
# 为保持简单与 100% 拦截率，暂不做豁免，靠关键词精确性控制误报。


def check_emergency(text: str) -> str | None:
    """若命中急症关键词返回命中的词，否则返回 None。"""
    if not text:
        return None
    for kw in EMERGENCY_KEYWORDS:
        if kw in text:
            return kw
    return None
