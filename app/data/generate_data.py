def _resolve_font() -> str:
    """按平台解析中文字体：Windows 用系统字体，Linux 用 Noto CJK。"""
    import os

    candidates = [
        ("SimHei", r"C:\Windows\Fonts\SimHei.ttf"),
        ("SimSun", r"C:\Windows\Fonts\simsun.ttc"),
        ("MicrosoftYaHei", r"C:\Windows\Fonts\msyh.ttc"),
        ("NotoSansCJK", "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"),
        ("NotoSerifCJK", "/usr/share/fonts/opentype/noto/NotoSerifCJK-Regular.ttc"),
        ("wqymicrohei", "/usr/share/fonts/truetype/wqy/wqy-microhei.ttc"),
    ]
    for name, path in candidates:
        if os.path.exists(path):
            try:
                from reportlab.pdfbase.ttfonts import TTFont

                subfont = 0 if path.lower().endswith(".ttc") else None
                pdfmetrics.registerFont(TTFont(name, path, subfontIndex=subfont))
                return name
            except Exception:
                continue
    from reportlab.pdfbase.cidfonts import UnicodeCIDFont

    pdfmetrics.registerFont(UnicodeCIDFont("STSong-Light"))
    return "STSong-Light"


_SECTIONS = [
    ("药品名称", "name"),
    ("规格", "spec"),
    ("成分", "composition"),
    ("适应症", "indications"),
    ("用法用量", "dosage"),
    ("不良反应", "adverse"),
    ("禁忌", "contraindications"),
    ("注意事项", "precautions"),
    ("特殊人群用药", "special"),
    ("药物相互作用", "interactions_text"),
    ("贮藏", "storage"),
]


def _interactions_text(drug: dict) -> str:
    if not drug["interactions"]:
        return "尚无充分证据显示本品与其他常用药物存在明确的相互作用，但合用时仍需谨慎。"
    lines = []
    for partner, level, desc in drug["interactions"]:
        lines.append(f"{partner}（风险：{level}）：{desc}")
    return "；".join(lines)


def _render_pdf(drug: dict, font_name: str, pdf_path: Path):
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("Title", parent=styles["Title"], fontName=font_name,
                                 fontSize=16, leading=22, spaceAfter=6)
    head_style = ParagraphStyle("Head", parent=styles["Heading2"], fontName=font_name,
                                fontSize=12, leading=16, textColor=colors.HexColor("#1a4f8b"),
                                spaceBefore=8, spaceAfter=2)
    body_style = ParagraphStyle("Body", parent=styles["BodyText"], fontName=font_name,
                                fontSize=10.5, leading=16, wordWrap="CJK")

    story = [Paragraph("药品说明书", title_style),
             Paragraph(f"{drug['name']}（{CATEGORY_NAMES[drug['cat']]}）", head_style),
             Spacer(1, 4)]
    for title, key in _SECTIONS:
        if key == "interactions_text":
            text = _interactions_text(drug)
        else:
            text = str(drug[key])
        story.append(Paragraph(f"【{title}】", head_style))
        story.append(Paragraph(text, body_style))
    doc = SimpleDocTemplate(str(pdf_path), pagesize=A4,
                            leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=18 * mm, bottomMargin=18 * mm,
                            title=f"{drug['name']}说明书", author="MedSafetyQA")
    doc.build(story)


def _render_txt(drug: dict, txt_path: Path):
    lines = [f"{drug['name']}（{CATEGORY_NAMES[drug['cat']]}）", "=" * 30]
    for title, key in _SECTIONS:
        text = _interactions_text(drug) if key == "interactions_text" else str(drug[key])
        lines.append(f"【{title}】{text}")
    txt_path.write_text("\n".join(lines), encoding="utf-8")


def generate_pdfs():
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    TEXT_DIR.mkdir(parents=True, exist_ok=True)
    font_name = _resolve_font()
    count = 0
    for drug in _DRUGS:
        cat_dir = PDF_DIR / drug["cat"]
        cat_dir.mkdir(parents=True, exist_ok=True)
        pdf_path = cat_dir / f"{drug['name']}.pdf"
        _render_pdf(drug, font_name, pdf_path)
        _render_txt(drug, TEXT_DIR / f"{drug['name']}.txt")
        count += 1
    return count


